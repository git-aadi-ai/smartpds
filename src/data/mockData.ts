// Helper to calculate days between dates
export const calculateAgeDays = (receivedDateStr: string, baseDateStr = '2026-10-23'): number => {
  const received = new Date(receivedDateStr).getTime();
  const base = new Date(baseDateStr).getTime();
  const diffTime = Math.max(0, base - received);
  return Math.floor(diffTime / (1000 * 60 * 60 * 24));
};

